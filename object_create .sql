
-- USER  
CREATE USER GATEONE IDENTIFIED BY ApiManager;
ALTER USER GATEONE
DEFAULT TABLESPACE DATA
TEMPORARY TABLESPACE TEMP;
  
GRANT UNLIMITED TABLESPACE TO GATEONE;
GRANT CONNECT, RESOURCE, DBA TO GATEONE;


-- TABLE
CREATE TABLE GATEONE.CONFIG  (	
	CNFNAME VARCHAR2(50 BYTE) NOT NULL ENABLE, 
	CNFVALUE VARCHAR2(250 BYTE) NOT NULL ENABLE,	 
	INFO     VARCHAR2(250 BYTE),
	PROCESS  VARCHAR2(150 BYTE), 
	CONTROL  VARCHAR2(150 BYTE)
); 

CREATE TABLE GATEONE.INBOX (
	ID NUMBER(9,0), 
	SENDER_NAME VARCHAR2(120 BYTE), 
	SENDER VARCHAR2(255 BYTE), 
	RECEIVER VARCHAR2(250 BYTE), 
	SUBJECT VARCHAR2(255 BYTE),
	MSG VARCHAR2(2000 BYTE), 
	SENTTIME VARCHAR2(100 BYTE), 
	RECEIVEDTIME VARCHAR2(100 BYTE), 
	OPERATOR VARCHAR2(120 BYTE), 
	MSGTYPE VARCHAR2(50 BYTE), 
	REFERENCE VARCHAR2(100 BYTE), 
	STATUS VARCHAR2(50 BYTE), 
	ERRORMSG VARCHAR2(50 BYTE), 
	ATTACH VARCHAR2(250 BYTE),  
	CONSTRAINT "GATEPARTNER_REF_UK" UNIQUE ("REFERENCE"),
	CONSTRAINT "GATEPARTNER_IN_PK" PRIMARY KEY ("ID")
);
 

CREATE OR REPLACE TRIGGER GATEONE.AUTONUM_INBOX 
  before INSERT ON GATEPONE.INBOX 
  FOR EACH ROW
     WHEN (new.id IS NULL) BEGIN
  SELECT NVL(MAX(id),0) + 1
  INTO :NEW.id
  FROM GATEONE.INBOX;
END;
/

ALTER TRIGGER GATEONE.AUTONUM_INBOX ENABLE;
 


